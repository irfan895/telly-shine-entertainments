import mongoose from "mongoose"

const contactSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      trim: true,
    },
    email: {
      type: String,
      required: true,
      trim: true,
      lowercase: true,
    },
    subject: {
      type: String,
      default: "General Inquiry",
      trim: true,
    },
    message: {
      type: String,
      required: true,
      trim: true,
    },
    status: {
      type: String,
      default: "unread",
    },
  },
  { timestamps: true, strict: false, collection: "contact_messages" }
)

const ContactMessage = mongoose.model("ContactMessage", contactSchema)

export default ContactMessage
